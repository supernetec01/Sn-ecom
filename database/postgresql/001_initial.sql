-- Ledger and audit records are append-only for ordinary application operations.
CREATE FUNCTION deny_ledger_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'append-only table: %', TG_TABLE_NAME USING ERRCODE = '23514';
END;
$$;
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['order_items','payment_transactions','payment_events','stock_movements',
    'audit_logs','order_status_history','loyalty_ledger','consent_events'] LOOP
    EXECUTE format('CREATE TRIGGER append_only BEFORE UPDATE OR DELETE ON supernet.%I FOR EACH ROW EXECUTE FUNCTION supernet.deny_ledger_mutation()', t);
  END LOOP;
END;
$$;
CREATE FUNCTION protect_order_amounts() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF ROW(NEW.subtotal_vnd,NEW.discount_vnd,NEW.points_discount_vnd,NEW.shipping_vnd,NEW.tax_vnd,NEW.total_vnd,NEW.currency)
    IS DISTINCT FROM ROW(OLD.subtotal_vnd,OLD.discount_vnd,OLD.points_discount_vnd,OLD.shipping_vnd,OLD.tax_vnd,OLD.total_vnd,OLD.currency) THEN
    RAISE EXCEPTION 'placed order amounts are immutable; use a separate adjustment workflow' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER immutable_amounts BEFORE UPDATE ON orders FOR EACH ROW EXECUTE FUNCTION protect_order_amounts();
-- Cross-row monetary rules require serializing on the order BEFORE writing a receipt/refund.
CREATE FUNCTION check_payment_balance() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE maximum bigint; received bigint; refunded bigint;
BEGIN
  SELECT total_vnd INTO maximum FROM supernet.orders WHERE id = NEW.order_id FOR UPDATE;
  SELECT coalesce(sum(amount_vnd) FILTER (WHERE kind='receipt'),0),
         coalesce(sum(amount_vnd) FILTER (WHERE kind='refund'),0)
    INTO received, refunded FROM supernet.payment_transactions WHERE order_id = NEW.order_id;
  received := received + CASE WHEN NEW.kind='receipt' THEN NEW.amount_vnd ELSE 0 END;
  refunded := refunded + CASE WHEN NEW.kind='refund' THEN NEW.amount_vnd ELSE 0 END;
  IF received > maximum OR refunded > received THEN
    RAISE EXCEPTION 'payment exceeds order total or refund exceeds receipts' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER payment_balance BEFORE INSERT ON payment_transactions
  FOR EACH ROW EXECUTE FUNCTION check_payment_balance();

-- Keep order subtotal equal to line snapshots, allowing header+lines in one transaction.
CREATE FUNCTION check_order_subtotal() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE oid bigint; expected bigint; actual bigint; n bigint;
BEGIN
  IF TG_TABLE_NAME = 'orders' THEN
    oid := NEW.id;
  ELSIF TG_OP = 'DELETE' THEN
    oid := OLD.order_id;
  ELSE
    oid := NEW.order_id;
    IF TG_OP='UPDATE' AND OLD.order_id <> NEW.order_id THEN
      RAISE EXCEPTION 'order items cannot change parent' USING ERRCODE='23514';
    END IF;
  END IF;
  SELECT subtotal_vnd INTO expected FROM supernet.orders WHERE id=oid;
  SELECT count(*),coalesce(sum(line_total_vnd),0) INTO n,actual FROM supernet.order_items WHERE order_id=oid;
  IF n=0 OR actual<>expected THEN
    RAISE EXCEPTION 'order subtotal does not match line snapshots' USING ERRCODE='23514';
  END IF;
  RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER header_subtotal AFTER INSERT OR UPDATE ON orders
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_order_subtotal();
CREATE CONSTRAINT TRIGGER line_subtotal AFTER INSERT OR UPDATE OR DELETE ON order_items
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_order_subtotal();

