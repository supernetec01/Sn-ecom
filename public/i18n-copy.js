export const dictionaries = {
  en: Object.fromEntries(rows.map(([vi,en])=>[vi,en])),
  'zh-TW': Object.fromEntries(rows.map(([vi,,zh])=>[vi,zh])),
};

export function interfaceText(source, language) {
  if (language === 'vi') return source;
  const dictionary = dictionaries[language] || {};
  if (Object.hasOwn(dictionary, source)) return dictionary[source];
  const en = language === 'en';
  const patterns = [
    [/^Trang (\d+)$/, n=>en?`Page ${n}`:`第 ${n} 頁`],
    [/^(\d+) sản phẩm$/, n=>en?`${n} products`:`${n} 件商品`],
    [/^Còn hàng · (\d+) sản phẩm$/, n=>en?`In stock · ${n} items`:`有現貨 · ${n} 件`],
    [/^Chỉ còn (\d+) sản phẩm\. Vui lòng điều chỉnh hoặc xóa khỏi giỏ\.$/, n=>en?`Only ${n} left. Adjust the quantity or remove this item.`:`僅剩 ${n} 件。請調整數量或移除商品。`],
    [/^Có (\d+) phường\/xã\/đặc khu thuộc tỉnh\/thành phố đã chọn\.$/, n=>en?`${n} wards / communes / special zones in the selected province / city.`:`所選省／市有 ${n} 個坊／社／特區。`],
    [/^Đơn hàng SN(\d+)$/, n=>en?`Order SN${n}`:`訂單 SN${n}`],
    [/^Đã tiếp nhận đơn SN(\d+)$/, n=>en?`Order SN${n} received`:`已收到訂單 SN${n}`],
    [/^Mã sản phẩm: (.+)$/, sku=>en?`SKU: ${sku}`:`商品編號：${sku}`],
    [/^Giao hàng tiêu chuẩn (.+)$/, fee=>en?`Standard delivery ${fee}`:`標準配送 ${fee}`],
    [/^Miễn phí vận chuyển từ (.+)$/, amount=>en?`Free delivery from ${amount}`:`免運門檻 ${amount}`],
    [/^Miễn phí giao hàng cho đơn từ (.+)$/, amount=>en?`Free delivery on orders from ${amount}`:`訂單滿 ${amount} 免運`],
    [/^© (\d{4}) (.+)\. Mọi quyền được bảo lưu\.$/, (year,brand)=>en?`© ${year} ${brand}. All rights reserved.`:`© ${year} ${brand}。版權所有。`],
    [/^Tiền hàng (.+) − giảm (.+) − điểm (.+) \+ giao (.+) = (.+)$/, (a,b,c,d,e)=>en?`Items ${a} − discount ${b} − points ${c} + delivery ${d} = ${e}`:`商品 ${a} − 折扣 ${b} − 點數 ${c} + 運費 ${d} = ${e}`],
  ];
  for (const [pattern,render] of patterns) {
    const match = source.match(pattern);
    if (match) return render(...match.slice(1));
  }
  return source;
}
