CREATE TABLE permissions (code text PRIMARY KEY, description text NOT NULL);
CREATE TABLE role_permissions (
  role_code text REFERENCES roles(code),
  permission_code text REFERENCES permissions(code),
  PRIMARY KEY(role_code, permission_code)
);
CREATE TABLE account_roles (
  account_id bigint REFERENCES accounts(id),
  role_code text REFERENCES roles(code),
  PRIMARY KEY(account_id, role_code)
);
CREATE TABLE sessions (
  token_hash text PRIMARY KEY CHECK (token_hash ~ '^[a-f0-9]{64}$'),
  account_id bigint NOT NULL REFERENCES accounts(id),
  csrf_hash text NOT NULL,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON sessions(account_id, expires_at);
CREATE TABLE auth_tokens (
  token_hash text PRIMARY KEY CHECK (token_hash ~ '^[a-f0-9]{64}$'),
  account_id bigint NOT NULL REFERENCES accounts(id),
  purpose text NOT NULL CHECK (purpose IN ('reset','verify')),
  expires_at timestamptz NOT NULL,
  used_at timestamptz
);
CREATE TABLE mfa_credentials (
  account_id bigint PRIMARY KEY REFERENCES accounts(id),
  secret_ciphertext bytea NOT NULL,
  key_version text NOT NULL,
  last_used_step bigint NOT NULL DEFAULT -1,
  enabled_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE mfa_recovery_codes (
  code_hash text PRIMARY KEY CHECK (code_hash ~ '^[a-f0-9]{64}$'),
  account_id bigint NOT NULL REFERENCES accounts(id),
  used_at timestamptz
);
CREATE TABLE customers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint UNIQUE REFERENCES accounts(id),
  name text NOT NULL,
  email text,
  phone text CHECK (phone IS NULL OR phone ~ '^\+?[0-9]{9,15}$'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE consent_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES customers(id),
  purpose text NOT NULL CHECK (purpose IN ('marketing_email','marketing_sms','analytics','terms')),
  policy_version text NOT NULL,
  granted boolean NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE customer_addresses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES customers(id),
  recipient text NOT NULL,
  phone text NOT NULL CHECK (phone ~ '^\+?[0-9]{9,15}$'),
  country text NOT NULL DEFAULT 'VN' CHECK (country = 'VN'),
  province_code text NOT NULL,
  province_name text NOT NULL,
  ward_code text NOT NULL,
  ward_name text NOT NULL,
  address_line text NOT NULL,
